      overrideFieldsForGroup: model.overrideFieldsForGroup,
      overrideGroupList: model.overrideGroupList,
      overrideLayouts: deps.overrideLayouts,
      overrideStatus: model.overrideStatus,
      pathCanReset: model.pathCanReset,
      pathEvidence: model.pathEvidence,
      pathIsInherited: model.pathIsInherited,
